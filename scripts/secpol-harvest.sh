#!/usr/bin/env bash
# Harvest the SYSTEM half of the secure-mode policy with secpolgenerate.
#   1. boot an --secpol=open image with target/secpol/kervix.secpol as the base
#      policy and every Kervix type held `restricted` (Kervix rules are written
#      by hand and must not grow by learning)
#   2. exercise everything the secure image will do: boot, ssh/scp, the Kervix
#      roles, kx-rogue, the operator's ledger export
#   3. save /dev/secpolgenerate/policy (only the rules the base policy lacks:
#      the system services and the admin shell) to target/secpol/system.secpol,
#      and the errors file (what the restricted Kervix types were refused)
# Review the diff before committing: secpolgenerate learns whatever happened.
# The secure image uses kervix.secpol + system.secpol + monitor.secpol
# (concatenated by tests/target/secpol.sh secure).
# Usage: scripts/secpol-harvest.sh
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
Q=scripts/qemu.sh
. tests/target/secpol-lib.sh
OUT=target/secpol/system.secpol

make -s target-x86_64 >/dev/null
$Q stop >/dev/null || true
KX_SNIPPETS=target/image/snippets \
KX_MKQNXIMAGE_EXTRA="--secpol=open --policy=/work/target/secpol/kervix.secpol --secure-procfs=yes" $Q image >/dev/null
$Q start >/dev/null && $Q wait 180 >/dev/null
$Q ssh "for t in $KX_TYPES; do grep -qx \"type \$t restricted\" /data/var/secpol/config || echo \"type \$t restricted\" >> /data/var/secpol/config; done; sync"
# reboot twice: the second boot is learned with the config in force from the start
for i in 1 2; do $Q stop >/dev/null; $Q start >/dev/null; $Q wait 180 >/dev/null; done

echo "== exercise"
$Q ssh "$KX_ROLES" >/dev/null 2>&1 || true
$Q ssh "on -T agentgw_t /system/bin/kervix/kx-rogue --kervixd-pid $(kx_kervixd_pid) >/dev/null; on -T agentgw_t -u 400:400 /system/bin/kervix/kx-rogue --kervixd-pid $(kx_kervixd_pid) >/dev/null; true"
# what the test harness itself does as the admin: inspect, logs, files, scp both ways
$Q ssh 'pidin -f an_ >/dev/null; pidin -p kervixd -F "%a" >/dev/null; slog2info >/dev/null; ls -l /data/kervix /tmp >/dev/null; cat /tmp/*.log >/dev/null; rm -rf /data/kervix/ledger /data/kervix/keys /tmp/h; mkdir -p /tmp/h; sync; true'
echo harvest > build/harvest.txt
$Q scp build/harvest.txt /tmp/h/
scp -q -O -r -i vm/ssh/kervix_ed25519 -P 2222 -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR root@127.0.0.1:/tmp/dossier build/harvest-dossier
rm -rf build/harvest-dossier build/harvest.txt

echo "== collect"
{
  echo "# SYSTEM half of the Kervix secure-mode policy. GENERATED by scripts/secpol-harvest.sh"
  echo "# (secpolgenerate on QNX 8.0, base policy target/secpol/kervix.secpol, Kervix types restricted)."
  echo "# Rules for the stock QNX services and the admin shell; Kervix rules live in kervix.secpol."
  echo "# Regenerate after changing the image or what the tests do; review every diff."
  echo
  # Kervix types are hand-written in kervix.secpol; secpolgenerate also reports
  # their (already granted) connects in ability form, so drop those blocks.
  # "default" only holds mkqnximage's open-mode libsecpol-gen symlink.
  $Q ssh 'cat /dev/secpolgenerate/policy' | KX_TYPES="$KX_TYPES" python3 -c '
import os,re,sys
kx=set(os.environ["KX_TYPES"].split())|{"default"}; keep=True
for l in sys.stdin:
    m=re.match(r"# === Rules for type (\S+) =", l)
    if m: keep=m.group(1) not in kx
    elif l.startswith("# === "): keep=True
    if keep: sys.stdout.write(l)'
} > "$OUT"
$Q ssh 'cat /dev/secpolgenerate/errors' > build/secpol-harvest-errors.txt
$Q ssh 'cat /dev/secpolgenerate/unused' > build/secpol-harvest-unused.txt
echo "wrote $OUT ($(grep -c '' "$OUT") lines); refusals of Kervix types: build/secpol-harvest-errors.txt"
