#!/usr/bin/env node
// Regenerate THIRD_PARTY.md from package-lock.json (npm) plus the fixed list of
// non-npm components. Run after any dependency change:  node tools/third-party.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
// packages whose package.json has no "license" field, checked by hand (their LICENSE file)
const MANUAL = { "webgl-constants": "MIT (LICENSE file)" };

const seen = new Map();
for (const [p, v] of Object.entries(lock.packages)) {
  if (!p.startsWith("node_modules/") || v.link) continue;
  const name = p.replace(/^.*node_modules\//, "");
  const key = `${name}@${v.version}`;
  if (!seen.has(key)) seen.set(key, { name, version: v.version, license: v.license ?? MANUAL[name] ?? "UNKNOWN", dev: !!v.dev });
}
const all = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const prod = all.filter((r) => !r.dev), dev = all.filter((r) => r.dev);
const unknown = all.filter((r) => r.license === "UNKNOWN");
if (unknown.length) { console.error(`licence unknown: ${unknown.map((r) => r.name).join(", ")} (add to MANUAL after checking)`); process.exit(1); }
const tally = (xs) => Object.entries(xs.reduce((m, r) => ((m[r.license] = (m[r.license] ?? 0) + 1), m), {})).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ");

const md = `# Third-party software

Kervix itself is Apache-2.0 (see [LICENSE](LICENSE)). It uses the following third-party software.
*Generated by \`node tools/third-party.mjs\` from \`package-lock.json\`; do not edit by hand.*

## Not redistributed: tools you install yourself

| Component | Licence | How Kervix uses it |
|---|---|---|
| **QNX Software Development Platform 8.0** (qcc/gcc 12, \`mkqnximage\`, \`secpolcompile\`, the QNX 8.0 OS image, **qcrypto** with its \`openssl-3\` plugin, slog2) | Proprietary, BlackBerry QNX. Used under the free *QNX Everywhere* non-commercial licence | Target toolchain and OS. **Nothing from the SDP is committed to this repository.** Images are built locally from your own SDP install. |
| QEMU | GPL-2.0 | Runs the QNX 8.0 x86_64 image on the development host. Not distributed. |
| Docker | Apache-2.0 (Engine) | Runs the SDP's Linux host tools on macOS. Not distributed. |
| Node.js | MIT | Runtime for the host tools. Not distributed. |

## In this repository

| Item | Origin | Licence |
|---|---|---|
| RFC 8032 Ed25519 test vector (\`tests/\`, \`spikes/\`) | IETF RFC 8032 §7.1, test 1 | IETF Trust (code components: BSD-3-Clause) |
| Synthetic drive cycle, scenarios, documents (\`scenarios/\`) | Written for Kervix; no third-party data | Apache-2.0 |
| 3D vehicle | Procedural (React Three Fiber primitives); no models, textures or brands | Apache-2.0 |

## npm packages used at run time (${prod.length})

Licences: ${tally(prod)}.

These run in the host tools (bridge, agent, verifier, policy compiler) or are bundled into the dashboard.

| Package | Version | Licence |
|---|---|---|
${prod.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join("\n")}

Notes:
- **\`@decionis/verify\`** (Apache-2.0) is an open-source AAC verifier by the same author that **predates the hackathon**; Kervix uses it as a dependency.
- **\`@anthropic-ai/sdk\`** and **\`@anthropic-ai/foundry-sdk\`** (Apache-2.0) are used only by the optional live agent.

## npm packages used only to build and test (${dev.length})

Licences: ${tally(dev)}. These are build tooling (TypeScript, Vite and its dependencies, type definitions) and are not part of any distributed artifact.

<details><summary>List</summary>

| Package | Version | Licence |
|---|---|---|
${dev.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join("\n")}

</details>
`;
fs.writeFileSync(path.join(root, "THIRD_PARTY.md"), md);
console.log(`THIRD_PARTY.md: ${prod.length} run-time + ${dev.length} build-time packages`);
